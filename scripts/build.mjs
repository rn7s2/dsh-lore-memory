/**
 * Build `src/` into the committed `lib/`:
 *
 * - `lib/index.js`: one ESM file for the Host, every dependency bundled
 *   except Node builtins. `native/` ships beside it.
 * - `lib/client.js`: the browser module the Harness module loader registers,
 *   with React supplied by the page rather than bundled.
 */
import { build } from 'esbuild'
import { mkdir, rm } from 'node:fs/promises'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const lib = join(root, 'lib')

await rm(lib, { recursive: true, force: true })
await mkdir(lib, { recursive: true })
await build({
  entryPoints: [join(root, 'src/index.ts')],
  outfile: join(lib, 'index.js'),
  bundle: true,
  format: 'esm',
  platform: 'node',
  target: 'node24',
  sourcemap: false,
  legalComments: 'none',
  banner: { js: '/* Generated by scripts/build.mjs from src/ — do not edit. */' },
  logLevel: 'warning',
})
console.log('built lib/index.js')

await build({
  entryPoints: [join(root, 'src/client/index.tsx')],
  outfile: join(lib, 'client.js'),
  bundle: true,
  format: 'cjs',
  platform: 'browser',
  target: 'es2022',
  jsx: 'automatic',
  external: ['react', 'react/jsx-runtime', 'react-dom', 'react-dom/client'],
  sourcemap: false,
  legalComments: 'none',
  banner: {
    js: [
      '/* Generated by scripts/build.mjs from src/ — do not edit. */',
      'window.__ModuleLoader__.load({',
      '  id: "dsh-lore-memory",',
      '  factory: (require) => {',
      '    var module = { exports: {} };',
      '    var exports = module.exports;',
    ].join('\n'),
  },
  footer: {
    js: ['    return module.exports;', '  },', '});'].join('\n'),
  },
  logLevel: 'warning',
})
console.log('built lib/client.js')
