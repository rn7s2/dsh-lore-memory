/**
 * Build `src/` into the committed `lib/index.js`: one ESM file for the Host,
 * every dependency bundled except Node builtins. `native/` ships beside `lib/`.
 */
import { build } from 'esbuild'
import { mkdir, rm } from 'node:fs/promises'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const lib = join(root, 'lib')

await rm(lib, { recursive: true, force: true })
await mkdir(lib, { recursive: true })
await build({
  entryPoints: [join(root, 'src/index.ts')],
  outfile: join(lib, 'index.js'),
  bundle: true,
  format: 'esm',
  platform: 'node',
  target: 'node24',
  sourcemap: false,
  legalComments: 'none',
  banner: { js: '/* Generated by scripts/build.mjs from src/ — do not edit. */' },
  logLevel: 'warning',
})
console.log('built lib/index.js')
