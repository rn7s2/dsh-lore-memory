import { readFileSync } from 'node:fs'
import { join } from 'node:path'
import { runInNewContext } from 'node:vm'

import { describe, expect, it, vi } from 'vitest'

import { tempDir } from './helpers.js'

const root = join(import.meta.dirname, '..')

describe('built bundle', () => {
  it('exports the Cordis plugin surface and finds its vendored tokenizer', async () => {
    // @ts-expect-error -- the built file has no declarations
    const lib = await import('../lib/index.js')
    expect(lib.name).toBe('lore-memory')
    expect(lib.inject).toEqual(['tools', 'systemPrompt'])
    expect(typeof lib.apply).toBe('function')
    expect(lib.Config({})).toEqual({ dbPath: '~/.dsh/lore-memory.db', searchLimitDefault: 8 })
    const host = { warnings: [] as string[] }
    const ctx = {
      tools: { register: () => () => undefined },
      systemPrompt: { section: () => () => undefined },
      get: () => undefined,
      on: () => () => undefined,
      effect: (fn: () => () => void) => void fn,
      inject: () => undefined,
      logger: { warn: (m: string) => void host.warnings.push(m) },
    }
    const { store } = lib.activate(ctx, { dbPath: join(tempDir(), 'db.sqlite') })
    const opened = await store
    expect(opened.status().state).toBe('ready')
    opened.close()
  })

  it('declares the bundle manifest, display metadata, and shipped files', () => {
    const pkg = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8'))
    expect(pkg.version).toBe('0.3.1')
    expect(pkg.os).toEqual(['darwin', 'linux'])
    expect(pkg.dsh.bundle.patch).toBe('./cordis.patch.yml')
    expect(pkg.dsh.client).toEqual({ platform: 'web', inject: ['@deepseek-ai/dsh-api-gateway', '@deepseek-ai/dsh-client-locale'] })
    expect(pkg.exports['./client']).toBe('./lib/client.js')
    expect(pkg.exports['./icon']).toBe('./icon.svg')
    expect(pkg.files).toEqual(expect.arrayContaining(['lib/**/*.js', 'native/**/*', 'locale/*.json', 'cordis.patch.yml', 'icon.svg']))
    for (const locale of ['en', 'zh']) {
      const meta = JSON.parse(readFileSync(join(root, 'locale', `${locale}.json`), 'utf8')).meta
      expect(meta.title.length).toBeGreaterThan(0)
      expect(meta.description.length).toBeGreaterThan(0)
    }
    expect(readFileSync(join(root, 'cordis.patch.yml'), 'utf8')).toContain('name: dsh-lore-memory')
    expect(readFileSync(join(root, 'icon.svg'), 'utf8')).toMatch(/^<svg [^>]*xmlns="http:\/\/www.w3.org\/2000\/svg"/)
  })

  it('ships the browser module in the loader format without bundling React or host packages', () => {
    const client = readFileSync(join(root, 'lib', 'client.js'), 'utf8')
    expect(client.startsWith('/* Generated by scripts/build.mjs from src/ — do not edit. */\nwindow.__ModuleLoader__.load({')).toBe(true)
    expect(client).toContain('id: "dsh-lore-memory"')
    expect(client).toMatch(/require\("react\/jsx-runtime"\)/)
    expect(client).not.toContain('@deepseek-ai/dsh-client-ui-primitives')
    expect(client).not.toContain('node:sqlite')
    const module = loadClientModule()
    expect(typeof module.apply).toBe('function')
    expect(module.inject).toEqual(['slots', 'locale', 'remote'])

    const host = readFileSync(join(root, 'lib', 'index.js'), 'utf8')
    expect(host).toContain('loreMemory')
  })

  it('applies the browser module: mounts the Remote, adds the page and the sidebar entry', async () => {
    const module = loadClientModule()
    let mounted: any
    const registrations: { options: any; component: unknown }[] = []
    const dictionaries: Record<string, Record<string, Record<string, string>>> = {}
    const ctx = {
      remote: {
        $mount: async (contribution: any) => {
          mounted = contribution
          return async () => undefined
        },
      },
      locale: {
        register: (namespace: string, dicts: Record<string, Record<string, string>>) => {
          dictionaries[namespace] = dicts
          return () => undefined
        },
        bind: (namespace: string) => (key: string) => `${namespace}.${key}`,
      },
      slots: {
        inject: (_name: string, callback: () => unknown) => {
          callback()
          return () => undefined
        },
        register: (options: any, component: unknown) => {
          registrations.push({ options, component })
          return {}
        },
      },
      effect: (execute: () => () => void) => {
        execute()
        return () => undefined
      },
      get: () => undefined,
    }
    const dispose = await module.apply(ctx)
    expect(mounted.package).toBe('dsh-lore-memory')
    expect(mounted.descriptors.map((descriptor: any) => descriptor.method)).toEqual([
      'overview',
      'entries',
      'create',
      'update',
      'delete',
    ])
    expect(dictionaries['loreMemory']?.['en']?.['panel']).toBe('Lore & Memory')
    expect(dictionaries['loreMemory']?.['zh']?.['panel']).toBe('Lore 与记忆')
    expect(registrations.map((registration) => registration.options.name)).toEqual(['main', 'sidebar.panellist'])
    expect(registrations[0]?.options).toMatchObject({ key: 'lore-memory', locale: 'loreMemory' })
    expect(registrations[1]?.options).toMatchObject({ id: 'lore-memory', order: 20 })
    expect(registrations[1]?.options.order).toBeGreaterThan(10)
    expect(registrations[1]?.options.label()).toBe('loreMemory.panel')
    await dispose()
  })

  it('stays inert when the Remote cannot mount, so the web boot survives', async () => {
    const consoleError = vi.fn()
    const module = loadClientModule({ error: consoleError } as unknown as Console)
    let slotCalls = 0
    const ctx = {
      remote: {
        $mount: async () => {
          throw new Error('client api: method conflicts with its namespace service')
        },
      },
      locale: {
        register: () => () => undefined,
        bind: () => (key: string) => key,
      },
      slots: {
        inject: () => {
          slotCalls += 1
          return () => undefined
        },
        register: () => ({}),
      },
      effect: (execute: () => () => void) => {
        execute()
        return () => undefined
      },
      get: () => undefined,
    }
    const dispose = await module.apply(ctx)
    expect(typeof dispose).toBe('function')
    expect(slotCalls).toBe(0)
    expect(consoleError).toHaveBeenCalledWith(expect.stringContaining('could not be set up'), expect.any(Error))
    await dispose()
  })
})

interface ClientModule {
  apply(context: unknown): Promise<() => Promise<void>>
  readonly inject: string[]
}

/** Evaluate the committed browser bundle as the page's loader would. */
function loadClientModule(consoleObject: Console = console): ClientModule {
  const client = readFileSync(join(root, 'lib', 'client.js'), 'utf8')
  let registered: { id: string; factory(require: (name: string) => unknown): Record<string, unknown> } | undefined
  runInNewContext(client, {
    window: { __ModuleLoader__: { load: (entry: typeof registered) => void (registered = entry) } },
    console: consoleObject,
  })
  if (registered === undefined) throw new Error('the client bundle did not register a module')
  const react = { useState: () => undefined, useEffect: () => undefined, useMemo: () => undefined, Fragment: Symbol('fragment') }
  const module = registered.factory((name) => (name === 'react' ? react : { jsx: () => null, jsxs: () => null }))
  return { apply: module['apply'] as ClientModule['apply'], inject: module['inject'] as string[] }
}
